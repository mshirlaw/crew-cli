//! The shared task list. Tasks are stored one per line in .crew/tasks.tsv (id, status, owner, title, notes);
//! tasks.md is regenerated after every change. Changes take a file lock, so agents can't lose each other's edits.

use crate::context::Ctx;
use crate::{ui, util};
use anyhow::{bail, Context, Result};
use std::fmt::Write;
use std::fs::OpenOptions;

/// The statuses a task can have.
pub const STATUSES: [&str; 5] = ["todo", "doing", "review", "blocked", "done"];

#[derive(Clone, Debug, PartialEq)]
pub struct Task {
    pub id: u32,
    pub status: String,
    pub owner: String,
    pub title: String,
    pub notes: String,
}

/// Replaces tabs and newlines with spaces so a value fits in one field.
fn one_line(text: &str) -> String {
    text.replace(['\t', '\n', '\r'], " ")
}

/// Parses tasks.tsv text.
pub fn parse(text: &str) -> Vec<Task> {
    text.lines()
        .filter_map(|line| {
            let mut fields = line.split('\t');
            let id = fields.next()?.parse().ok()?;
            let mut next = || fields.next().unwrap_or("").to_string();
            Some(Task { id, status: next(), owner: next(), title: next(), notes: next() })
        })
        .collect()
}

/// Writes tasks as tasks.tsv text.
pub fn to_tsv(tasks: &[Task]) -> String {
    tasks.iter().fold(String::new(), |mut out, t| {
        let _ = writeln!(out, "{}\t{}\t{}\t{}\t{}", t.id, t.status, t.owner, t.title, t.notes);
        out
    })
}

/// Writes tasks as the tasks.md table agents read.
pub fn render(tasks: &[Task]) -> String {
    let mut out = String::from(
        "# Tasks\n\n<!-- Generated by crew. Change tasks with: crew task add / set / done -->\n\n\
         | id | status | owner | task | notes |\n|----|--------|-------|------|-------|\n",
    );
    for t in tasks {
        let cell = |s: &str| s.replace('|', "/");
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} |",
            t.id,
            cell(&t.status),
            cell(&t.owner),
            cell(&t.title),
            cell(&t.notes)
        );
    }
    out
}

/// Reads the current tasks.
pub fn load(ctx: &Ctx) -> Vec<Task> {
    parse(&std::fs::read_to_string(ctx.file("tasks.tsv")).unwrap_or_default())
}

/// Saves tasks and regenerates tasks.md.
fn save(ctx: &Ctx, tasks: &[Task]) -> Result<()> {
    util::write_atomic(&ctx.file("tasks.tsv"), &to_tsv(tasks))?;
    util::write_atomic(&ctx.file("tasks.md"), &render(tasks))
}

/// Runs a change to the tasks while holding the task lock.
fn with_lock<T>(ctx: &Ctx, change: impl FnOnce(&mut Vec<Task>) -> Result<T>) -> Result<T> {
    std::fs::create_dir_all(ctx.state.dir())?;
    let lock_path = ctx.state.dir().join("tasks.lock");
    let lock = OpenOptions::new()
        .create(true)
        .truncate(false)
        .write(true)
        .open(&lock_path)
        .with_context(|| format!("could not open {}", lock_path.display()))?;
    lock.lock().context("could not lock the task list")?;
    let mut tasks = load(ctx);
    let result = change(&mut tasks)?;
    save(ctx, &tasks)?;
    Ok(result)
}

/// Moves a hand-written tasks.md from crew 0.3 or earlier aside, so the generated one can replace it.
pub fn migrate_old_tasks(ctx: &Ctx) -> Result<()> {
    if ctx.file("tasks.tsv").exists() {
        return Ok(());
    }
    let old = std::fs::read_to_string(ctx.file("tasks.md")).unwrap_or_default();
    if old.lines().filter(|l| l.starts_with('|')).count() > 2 {
        std::fs::rename(ctx.file("tasks.md"), ctx.file("tasks-old.md"))?;
        ui::info("moved your old task list to .crew/tasks-old.md; add tasks again with crew task add");
    }
    save(ctx, &[])
}

/// Ids of a role's tasks that are todo or doing.
pub fn open_tasks(ctx: &Ctx, role: &str) -> Vec<u32> {
    load(ctx)
        .into_iter()
        .filter(|t| t.owner == role && (t.status == "todo" || t.status == "doing"))
        .map(|t| t.id)
        .collect()
}

/// Fails unless the owner is empty, "human", or a role.
fn check_owner(ctx: &Ctx, owner: &str) -> Result<()> {
    if owner.is_empty() || owner == "human" || ctx.role_exists(owner) {
        Ok(())
    } else {
        bail!("no role '{owner}' (roles: {})", ctx.roles().join(" "))
    }
}

/// Fails if no task has this id.
fn check_task(ctx: &Ctx, id: u32) -> Result<()> {
    if load(ctx).iter().any(|t| t.id == id) {
        Ok(())
    } else {
        bail!("no task {id}")
    }
}

/// crew tasks / crew task list: prints the task list.
pub fn cmd_list(ctx: &Ctx) -> Result<()> {
    ctx.require_crew()?;
    migrate_old_tasks(ctx)?;
    print!("{}", std::fs::read_to_string(ctx.file("tasks.md")).unwrap_or_default());
    Ok(())
}

/// crew task add: adds a task and prints its id.
pub fn cmd_add(ctx: &Ctx, title: &[String], owner: Option<&str>, notes: Option<&str>) -> Result<()> {
    ctx.require_crew()?;
    migrate_old_tasks(ctx)?;
    let title = one_line(&title.join(" "));
    if title.trim().is_empty() {
        bail!("usage: crew task add \"title\" [--owner role] [--notes \"...\"]");
    }
    let owner = one_line(owner.unwrap_or(""));
    check_owner(ctx, &owner)?;
    let notes = one_line(notes.unwrap_or(""));
    let id = with_lock(ctx, |tasks| {
        let id = tasks.iter().map(|t| t.id).max().unwrap_or(0) + 1;
        tasks.push(Task { id, status: "todo".into(), owner: owner.clone(), title: title.clone(), notes });
        Ok(id)
    })?;
    let for_owner = if owner.is_empty() { String::new() } else { format!(" for {owner}") };
    ui::ok(format!("task {id} added{for_owner}: {title}"));
    Ok(())
}

/// crew task set: changes a task's status, owner or notes, e.g. status=review owner=reviewer.
pub fn cmd_set(ctx: &Ctx, id: u32, changes: &[String]) -> Result<()> {
    ctx.require_crew()?;
    migrate_old_tasks(ctx)?;
    check_task(ctx, id)?;
    if changes.is_empty() {
        bail!("usage: crew task set <id> status=<s> owner=<role> notes=\"...\"");
    }
    let mut parsed = Vec::new();
    for change in changes {
        let (field, value) = change.split_once('=').unwrap_or((change.as_str(), ""));
        match field {
            "status" if !STATUSES.contains(&value) => bail!("status must be one of: {}", STATUSES.join(" ")),
            "owner" => check_owner(ctx, value)?,
            "status" | "notes" => {}
            _ => bail!("unknown field '{change}' (use status=, owner= or notes=)"),
        }
        parsed.push((field.to_string(), one_line(value)));
    }
    with_lock(ctx, |tasks| {
        if let Some(task) = tasks.iter_mut().find(|t| t.id == id) {
            for (field, value) in parsed {
                match field.as_str() {
                    "status" => task.status = value,
                    "owner" => task.owner = value,
                    _ => task.notes = value,
                }
            }
        }
        Ok(())
    })?;
    ui::ok(format!("task {id} updated"));
    Ok(())
}

/// crew task done: marks a task done, optionally replacing its notes.
pub fn cmd_done(ctx: &Ctx, id: u32, notes: &[String]) -> Result<()> {
    ctx.require_crew()?;
    migrate_old_tasks(ctx)?;
    check_task(ctx, id)?;
    let notes = one_line(&notes.join(" "));
    with_lock(ctx, |tasks| {
        if let Some(task) = tasks.iter_mut().find(|t| t.id == id) {
            task.status = "done".into();
            if !notes.is_empty() {
                task.notes = notes;
            }
        }
        Ok(())
    })?;
    ui::ok(format!("task {id} done"));
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tsv_round_trips() {
        let tasks = vec![Task {
            id: 1,
            status: "todo".into(),
            owner: "builder".into(),
            title: "Build it".into(),
            notes: "C:\\new folder".into(),
        }];
        assert_eq!(parse(&to_tsv(&tasks)), tasks);
    }

    #[test]
    fn table_cells_escape_pipes() {
        let tasks = vec![Task {
            id: 2,
            status: "done".into(),
            owner: String::new(),
            title: "a|b".into(),
            notes: String::new(),
        }];
        assert!(render(&tasks).contains("| 2 | done |  | a/b |  |"));
    }

    #[test]
    fn values_stay_on_one_line() {
        assert_eq!(one_line("a\tb\nc"), "a b c");
    }
}
