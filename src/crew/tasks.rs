// Tasks live in .crew/tasks.tsv (id, status, owner, title, notes) and tasks.md is regenerated on every change.
// Changes hold a file lock, so agents updating tasks at the same time can't lose each other's edits.

use super::context::Ctx;
use crate::util::{self, ui};
use anyhow::{Context, Result};
use std::fmt::Write;
use std::fs::OpenOptions;

pub const STATUSES: [&str; 5] = ["todo", "doing", "review", "blocked", "done"];

#[derive(Clone, Debug, PartialEq)]
pub struct Task {
    pub id: u32,
    pub status: String,
    pub owner: String,
    pub title: String,
    pub notes: String,
}

pub fn one_line(text: &str) -> String {
    text.replace(['\t', '\n', '\r'], " ")
}

pub fn parse(text: &str) -> Vec<Task> {
    text.lines()
        .filter_map(|line| {
            let mut fields = line.split('\t');
            let id = fields.next()?.parse().ok()?;
            let mut next = || fields.next().unwrap_or("").to_string();
            Some(Task { id, status: next(), owner: next(), title: next(), notes: next() })
        })
        .collect()
}

pub fn to_tsv(tasks: &[Task]) -> String {
    tasks.iter().fold(String::new(), |mut out, t| {
        let _ = writeln!(out, "{}\t{}\t{}\t{}\t{}", t.id, t.status, t.owner, t.title, t.notes);
        out
    })
}

pub fn render(tasks: &[Task]) -> String {
    let mut out = String::from(
        "# Tasks\n\n<!-- Generated by crew. Change tasks with: crew task add / set / done -->\n\n\
         | id | status | owner | task | notes |\n|----|--------|-------|------|-------|\n",
    );
    let cell = |s: &str| s.replace('|', "/");
    for t in tasks {
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} |",
            t.id,
            cell(&t.status),
            cell(&t.owner),
            cell(&t.title),
            cell(&t.notes)
        );
    }
    out
}

pub fn load(ctx: &Ctx) -> Vec<Task> {
    parse(&std::fs::read_to_string(ctx.file("tasks.tsv")).unwrap_or_default())
}

fn save(ctx: &Ctx, tasks: &[Task]) -> Result<()> {
    util::write_atomic(&ctx.file("tasks.tsv"), &to_tsv(tasks))?;
    util::write_atomic(&ctx.file("tasks.md"), &render(tasks))
}

fn with_lock<T>(ctx: &Ctx, change: impl FnOnce(&mut Vec<Task>) -> T) -> Result<T> {
    std::fs::create_dir_all(ctx.state.dir())?;
    let lock_path = ctx.state.dir().join("tasks.lock");
    let lock = OpenOptions::new()
        .create(true)
        .truncate(false)
        .write(true)
        .open(&lock_path)
        .with_context(|| format!("could not open {}", lock_path.display()))?;
    lock.lock().context("could not lock the task list")?;
    let mut tasks = load(ctx);
    let result = change(&mut tasks);
    save(ctx, &tasks)?;
    Ok(result)
}

pub fn add(ctx: &Ctx, owner: &str, title: &str, notes: &str) -> Result<u32> {
    with_lock(ctx, |tasks| {
        let id = tasks.iter().map(|t| t.id).max().unwrap_or(0) + 1;
        tasks.push(Task { id, status: "todo".into(), owner: owner.into(), title: title.into(), notes: notes.into() });
        id
    })
}

pub fn update(ctx: &Ctx, id: u32, changes: &[(String, String)]) -> Result<()> {
    with_lock(ctx, |tasks| {
        if let Some(task) = tasks.iter_mut().find(|t| t.id == id) {
            for (field, value) in changes {
                match field.as_str() {
                    "status" => task.status.clone_from(value),
                    "owner" => task.owner.clone_from(value),
                    _ => task.notes.clone_from(value),
                }
            }
        }
    })
}

pub fn exists(ctx: &Ctx, id: u32) -> bool {
    load(ctx).iter().any(|t| t.id == id)
}

pub fn open_for(ctx: &Ctx, role: &str) -> Vec<u32> {
    load(ctx)
        .into_iter()
        .filter(|t| t.owner == role && (t.status == "todo" || t.status == "doing"))
        .map(|t| t.id)
        .collect()
}

// crew 0.3 and earlier had a hand-written tasks.md; move it aside so the generated one can replace it.
pub fn migrate_old_tasks(ctx: &Ctx) -> Result<()> {
    if ctx.file("tasks.tsv").exists() {
        return Ok(());
    }
    let old = std::fs::read_to_string(ctx.file("tasks.md")).unwrap_or_default();
    if old.lines().filter(|l| l.starts_with('|')).count() > 2 {
        std::fs::rename(ctx.file("tasks.md"), ctx.file("tasks-old.md"))?;
        ui::info("moved your old task list to .crew/tasks-old.md; add tasks again with crew task add");
    }
    save(ctx, &[])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tsv_round_trips() {
        let tasks = vec![Task {
            id: 1,
            status: "todo".into(),
            owner: "builder".into(),
            title: "Build it".into(),
            notes: "C:\\new folder".into(),
        }];
        assert_eq!(parse(&to_tsv(&tasks)), tasks);
    }

    #[test]
    fn table_cells_escape_pipes() {
        let tasks = vec![Task {
            id: 2,
            status: "done".into(),
            owner: String::new(),
            title: "a|b".into(),
            notes: String::new(),
        }];
        assert!(render(&tasks).contains("| 2 | done |  | a/b |  |"));
    }

    #[test]
    fn values_stay_on_one_line() {
        assert_eq!(one_line("a\tb\nc"), "a b c");
    }
}
