// Tasks live in .crew/tasks.tsv (id, status, owner, title, notes) and tasks.md is regenerated on every change.
// Changes hold a file lock, so agents updating tasks at the same time can't lose each other's edits.

use super::context::Ctx;
use crate::util;
use anyhow::{Context, Result};
use std::fmt::Write;
use std::fs::OpenOptions;

pub const STATUSES: [&str; 5] = ["todo", "doing", "review", "blocked", "done"];

#[derive(Clone, Debug, PartialEq)]
pub struct Task {
    pub id: u32,
    pub status: String,
    pub owner: String,
    pub title: String,
    pub notes: String,
}

pub fn one_line(text: &str) -> String {
    text.replace(['\t', '\n', '\r'], " ")
}

pub fn parse(text: &str) -> Vec<Task> {
    text.lines()
        .filter_map(|line| {
            let mut fields = line.split('\t');
            let id = fields.next()?.parse().ok()?;
            let mut next = || fields.next().unwrap_or("").to_string();
            Some(Task { id, status: next(), owner: next(), title: next(), notes: next() })
        })
        .collect()
}

pub fn to_tsv(tasks: &[Task]) -> String {
    tasks.iter().fold(String::new(), |mut out, t| {
        let _ = writeln!(out, "{}\t{}\t{}\t{}\t{}", t.id, t.status, t.owner, t.title, t.notes);
        out
    })
}

pub fn render(tasks: &[Task]) -> String {
    let mut out = String::from(
        "# Tasks\n\n<!-- Generated by crew. Change tasks with: crew task add / set / done -->\n\n\
         | id | status | owner | task | notes |\n|----|--------|-------|------|-------|\n",
    );
    let cell = |s: &str| s.replace('|', "/");
    for t in tasks {
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} |",
            t.id,
            cell(&t.status),
            cell(&t.owner),
            cell(&t.title),
            cell(&t.notes)
        );
    }
    out
}

pub fn load(ctx: &Ctx) -> Vec<Task> {
    parse(&std::fs::read_to_string(ctx.file("tasks.tsv")).unwrap_or_default())
}

fn save(ctx: &Ctx, tasks: &[Task]) -> Result<()> {
    util::write_atomic(&ctx.file("tasks.tsv"), &to_tsv(tasks))?;
    util::write_atomic(&ctx.file("tasks.md"), &render(tasks))
}

fn with_lock<T>(ctx: &Ctx, change: impl FnOnce(&mut Vec<Task>) -> T) -> Result<T> {
    std::fs::create_dir_all(ctx.state.dir())?;
    let lock_path = ctx.state.dir().join("tasks.lock");
    let lock = OpenOptions::new()
        .create(true)
        .truncate(false)
        .write(true)
        .open(&lock_path)
        .with_context(|| format!("could not open {}", lock_path.display()))?;
    lock.lock().context("could not lock the task list")?;
    let mut tasks = load(ctx);
    let result = change(&mut tasks);
    save(ctx, &tasks)?;
    Ok(result)
}

pub fn add(ctx: &Ctx, owner: &str, title: &str, notes: &str) -> Result<u32> {
    with_lock(ctx, |tasks| {
        let id = tasks.iter().map(|t| t.id).max().unwrap_or(0) + 1;
        tasks.push(Task { id, status: "todo".into(), owner: owner.into(), title: title.into(), notes: notes.into() });
        id
    })
}

pub fn update(ctx: &Ctx, id: u32, changes: &[(String, String)]) -> Result<()> {
    with_lock(ctx, |tasks| {
        if let Some(task) = tasks.iter_mut().find(|t| t.id == id) {
            for (field, value) in changes {
                match field.as_str() {
                    "status" => task.status.clone_from(value),
                    "owner" => task.owner.clone_from(value),
                    _ => task.notes.clone_from(value),
                }
            }
        }
    })
}

pub fn exists(ctx: &Ctx, id: u32) -> bool {
    load(ctx).iter().any(|t| t.id == id)
}

pub fn open_for(ctx: &Ctx, role: &str) -> Vec<u32> {
    load(ctx)
        .into_iter()
        .filter(|t| t.owner == role && (t.status == "todo" || t.status == "doing"))
        .map(|t| t.id)
        .collect()
}

pub fn init(ctx: &Ctx) -> Result<()> {
    if ctx.file("tasks.tsv").exists() {
        return Ok(());
    }
    save(ctx, &[])
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::crew::testutil::{fixture, ROLES};

    #[test]
    fn tsv_round_trips() {
        let tasks = vec![Task {
            id: 1,
            status: "todo".into(),
            owner: "builder".into(),
            title: "Build it".into(),
            notes: "C:\\new folder".into(),
        }];
        assert_eq!(parse(&to_tsv(&tasks)), tasks);
    }

    #[test]
    fn table_cells_escape_pipes() {
        let tasks = vec![Task {
            id: 2,
            status: "done".into(),
            owner: String::new(),
            title: "a|b".into(),
            notes: String::new(),
        }];
        assert!(render(&tasks).contains("| 2 | done |  | a/b |  |"));
    }

    #[test]
    fn values_stay_on_one_line() {
        assert_eq!(one_line("a\tb\nc"), "a b c");
    }

    fn change(field: &str, value: &str) -> Vec<(String, String)> {
        vec![(field.to_string(), value.to_string())]
    }

    #[test]
    fn ids_count_up_from_one_and_new_tasks_are_todo() {
        let f = fixture(ROLES);
        assert_eq!(add(&f.ctx, "builder", "first", "n1").unwrap(), 1);
        assert_eq!(add(&f.ctx, "reviewer", "second", "").unwrap(), 2);
        let tasks = load(&f.ctx);
        assert_eq!(
            tasks[0],
            Task { id: 1, status: "todo".into(), owner: "builder".into(), title: "first".into(), notes: "n1".into() }
        );
        assert_eq!(tasks[1].status, "todo");
    }

    #[test]
    fn ids_are_not_reused_after_the_highest_is_done() {
        let f = fixture(ROLES);
        add(&f.ctx, "builder", "a", "").unwrap();
        update(&f.ctx, 1, &change("status", "done")).unwrap();
        assert_eq!(add(&f.ctx, "builder", "b", "").unwrap(), 2);
    }

    #[test]
    fn every_change_regenerates_tasks_md() {
        let f = fixture(ROLES);
        add(&f.ctx, "builder", "ship it", "").unwrap();
        let md = std::fs::read_to_string(f.ctx.file("tasks.md")).unwrap();
        assert!(md.contains("| 1 | todo | builder | ship it |  |"));
        update(&f.ctx, 1, &change("status", "doing")).unwrap();
        let md = std::fs::read_to_string(f.ctx.file("tasks.md")).unwrap();
        assert!(md.contains("| 1 | doing | builder | ship it |  |"));
    }

    #[test]
    fn update_changes_only_the_named_fields_of_that_task() {
        let f = fixture(ROLES);
        add(&f.ctx, "builder", "a", "old").unwrap();
        add(&f.ctx, "builder", "b", "keep").unwrap();
        let changes = vec![("owner".to_string(), "reviewer".to_string()), ("notes".to_string(), "new".to_string())];
        update(&f.ctx, 1, &changes).unwrap();
        let tasks = load(&f.ctx);
        assert_eq!(
            (tasks[0].owner.as_str(), tasks[0].notes.as_str(), tasks[0].status.as_str()),
            ("reviewer", "new", "todo")
        );
        assert_eq!((tasks[1].owner.as_str(), tasks[1].notes.as_str()), ("builder", "keep"));
    }

    #[test]
    fn updating_an_unknown_task_changes_nothing() {
        let f = fixture(ROLES);
        add(&f.ctx, "builder", "a", "").unwrap();
        update(&f.ctx, 9, &change("status", "done")).unwrap();
        assert_eq!(load(&f.ctx).len(), 1);
        assert_eq!(load(&f.ctx)[0].status, "todo");
    }

    #[test]
    fn exists_checks_the_id() {
        let f = fixture(ROLES);
        add(&f.ctx, "builder", "a", "").unwrap();
        assert!(exists(&f.ctx, 1));
        assert!(!exists(&f.ctx, 2));
    }

    #[test]
    fn open_for_counts_only_todo_and_doing_tasks_of_the_owner() {
        let f = fixture(ROLES);
        for status in ["todo", "doing", "review", "blocked", "done"] {
            let id = add(&f.ctx, "builder", status, "").unwrap();
            update(&f.ctx, id, &change("status", status)).unwrap();
        }
        add(&f.ctx, "reviewer", "theirs", "").unwrap();
        assert_eq!(open_for(&f.ctx, "builder"), [1, 2]);
        assert_eq!(open_for(&f.ctx, "reviewer"), [6]);
        assert!(open_for(&f.ctx, "lead").is_empty());
    }

    #[test]
    fn init_creates_empty_files_and_keeps_existing_tasks() {
        let f = fixture(ROLES);
        init(&f.ctx).unwrap();
        assert!(f.ctx.file("tasks.tsv").exists());
        assert!(std::fs::read_to_string(f.ctx.file("tasks.md")).unwrap().contains("| id | status |"));
        add(&f.ctx, "builder", "a", "").unwrap();
        init(&f.ctx).unwrap();
        assert_eq!(load(&f.ctx).len(), 1);
    }

    #[test]
    fn parse_skips_junk_and_fills_missing_fields() {
        let tasks = parse("not-a-number\tx\n\n3\tdoing\n");
        assert_eq!(tasks.len(), 1);
        assert_eq!(
            tasks[0],
            Task { id: 3, status: "doing".into(), owner: String::new(), title: String::new(), notes: String::new() }
        );
    }

    #[test]
    fn many_threads_adding_at_once_lose_nothing() {
        let f = fixture(ROLES);
        let (crew, state) = (f.ctx.crew.clone(), f.ctx.state.dir().to_path_buf());
        let handles: Vec<_> = (0..8)
            .map(|i| {
                let (crew, state) = (crew.clone(), state.clone());
                std::thread::spawn(move || {
                    let ctx = crate::crew::testutil::ctx_at(&crew, &state);
                    for n in 0..5 {
                        add(&ctx, "builder", &format!("t{i}-{n}"), "").unwrap();
                    }
                })
            })
            .collect();
        for handle in handles {
            handle.join().unwrap();
        }
        let tasks = load(&f.ctx);
        assert_eq!(tasks.len(), 40);
        let mut ids: Vec<u32> = tasks.iter().map(|t| t.id).collect();
        ids.sort_unstable();
        ids.dedup();
        assert_eq!(ids.len(), 40);
    }
}
