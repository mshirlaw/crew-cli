//! crew setup: creates .crew/ with a config, role files, board and tasks. Also writes PROTOCOL.md
//! and upgrades files from older versions.

use crate::config::util_first_installed;
use crate::context::Ctx;
use crate::{tasks, templates, ui, util};
use anyhow::{bail, Result};
use std::path::Path;

/// crew setup: creates .crew/ if it doesn't exist, then lists the roles.
pub fn cmd_setup(ctx: &mut Ctx) -> Result<()> {
    if ctx.require_crew().is_ok() {
        ui::info(format!("crew already set up in {}", ctx.crew.display()));
        return write_protocol(ctx);
    }
    create(ctx)?;
    ui::ok(format!("crew set up in {} (multiplexer: {})", ctx.crew.display(), ctx.mux.name()));
    println!();
    crate::roles::cmd_list(ctx)?;
    println!(
        "\n{} crew start   {}",
        ui::bold("Next:"),
        ui::dim("(customise first with crew role edit / crew role add / crew config edit)")
    );
    Ok(())
}

/// Creates .crew/ and everything in it.
pub fn create(ctx: &mut Ctx) -> Result<()> {
    if !util::run_ok("git", &["-C", &ctx.root.display().to_string(), "rev-parse", "--verify", "-q", "HEAD"]) {
        bail!("this repo has no commits yet. Make one first.");
    }
    std::fs::create_dir_all(ctx.file("roles"))?;
    std::fs::create_dir_all(ctx.file("notes"))?;
    std::fs::create_dir_all(ctx.state.dir())?;
    write_repo_config(ctx)?;
    ctx.reload()?;
    write_role_files(ctx)?;
    write_shared_files(ctx)?;
    write_protocol(ctx)?;
    hide_from_git(ctx)
}

/// Writes .crew/config.toml, taking roles from your global config if it has any.
fn write_repo_config(ctx: &Ctx) -> Result<()> {
    let root = ctx.root.display().to_string();
    let base = util::run_out("git", &["-C", &root, "symbolic-ref", "--short", "HEAD"])
        .or_else(|| util::run_out("git", &["-C", &root, "rev-parse", "--short", "HEAD"]))
        .map(|s| s.trim().to_string())
        .unwrap_or_else(|| "main".to_string());
    let roles = if ctx.config.global_has_roles() {
        format!("\n{}", ctx.config.global_roles_text())
    } else {
        if !["claude", "codex", "gemini"].iter().any(|a| util::has(a)) {
            ui::warn("none of claude, codex or gemini found. Edit .crew/config.toml");
        }
        templates::default_roles(
            &util_first_installed(&["claude", "codex", "gemini"]),
            &util_first_installed(&["codex", "claude", "gemini"]),
            &util_first_installed(&["gemini", "claude", "codex"]),
        )
    };
    std::fs::write(ctx.file("config.toml"), templates::repo_config_header(&base) + &roles)?;
    Ok(())
}

/// Creates a role file for every role that doesn't have one yet.
fn write_role_files(ctx: &Ctx) -> Result<()> {
    for role in ctx.roles() {
        let path = ctx.file(&format!("roles/{role}.md"));
        if !path.exists() {
            std::fs::write(path, templates::role_template(&role))?;
        }
    }
    Ok(())
}

/// Creates an empty board and task list.
fn write_shared_files(ctx: &Ctx) -> Result<()> {
    if !ctx.file("board.md").exists() {
        std::fs::write(ctx.file("board.md"), "# Crew board\n\n")?;
    }
    tasks::migrate_old_tasks(ctx)
}

/// Adds .crew/ to this clone's private git ignore list (.git/info/exclude).
fn hide_from_git(ctx: &Ctx) -> Result<()> {
    let root = ctx.root.display().to_string();
    let Some(path) = util::run_out("git", &["-C", &root, "rev-parse", "--git-path", "info/exclude"]) else {
        return Ok(());
    };
    let path = Path::new(path.trim());
    let path = if path.is_absolute() { path.to_path_buf() } else { ctx.root.join(path) };
    let text = std::fs::read_to_string(&path).unwrap_or_default();
    if !text.lines().any(|line| line.trim() == ".crew/") {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)?;
        }
        let separator = if text.is_empty() || text.ends_with('\n') { "" } else { "\n" };
        std::fs::write(&path, format!("{text}{separator}.crew/\n"))?;
    }
    Ok(())
}

/// Writes PROTOCOL.md: who's who, plus the rules every agent follows.
pub fn write_protocol(ctx: &Ctx) -> Result<()> {
    let base = ctx.base_branch();
    let mut text = format!(
        "# Crew protocol (generated by `crew`; edit roles/*.md instead)\n\n\
         You are one agent in a crew working on the repo at `{}`.\n\
         Shared crew folder: `{}`  (board.md, tasks.md, notes/, roles/)\n\
         Base branch: `{base}`\n\n\
         ## Team\n| role | agent | branch | works in |\n|------|-------|--------|----------|\n",
        ctx.root.display(),
        ctx.crew.display()
    );
    for role in ctx.roles() {
        let branch = if ctx.config.role_has_worktree(&role) {
            format!("crew/{role}")
        } else {
            format!("{base} (main checkout)")
        };
        text.push_str(&format!(
            "| {role} | {} | {branch} | {} |\n",
            ctx.config.role_agent(&role),
            ctx.role_dir(&role).display()
        ));
    }
    text.push_str(templates::PROTOCOL_RULES);
    std::fs::write(ctx.file("PROTOCOL.md"), text)?;
    Ok(())
}

/// Converts an old .crew/crew.conf roster (crew 0.2) into .crew/config.toml.
pub fn migrate_old_roster(crew: &Path) -> Result<()> {
    let old = crew.join("crew.conf");
    let new = crew.join("config.toml");
    if !old.is_file() || new.exists() {
        return Ok(());
    }
    let base =
        std::fs::read_to_string(crew.join("base")).map(|s| s.trim().to_string()).unwrap_or_else(|_| "main".into());
    let mut text = templates::repo_config_header(&base);
    for line in std::fs::read_to_string(&old)?.lines() {
        let fields: Vec<&str> = line.split_whitespace().collect();
        if fields.len() < 2 || fields[0].starts_with('#') {
            continue;
        }
        let worktree = fields.get(2) != Some(&"no");
        text.push_str(&format!("\n[roles.{}]\nagent = \"{}\"\nworktree = {worktree}\n", fields[0], fields[1]));
    }
    std::fs::write(&new, text)?;
    std::fs::rename(&old, crew.join("crew.conf.old"))?;
    ui::info("converted .crew/crew.conf to .crew/config.toml");
    Ok(())
}
